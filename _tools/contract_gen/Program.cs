using System.ComponentModel;
using System.Globalization;
using System.Text;
using System.Text.Json;
using WaveDudeNext.Model;
using WaveDudeNext.Server.Projects;

var root = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "../../../../../"));
if (args is ["--fixtures", var fixturePath])
{
	var examples = Directory.GetFiles(Path.Combine(root, "Examples"), "*.wdproj", SearchOption.AllDirectories)
		.Order(StringComparer.Ordinal).Select(path => new ProjectDocument(Project.Load(path)).Write()).ToList();
	var allParts = new Project();
	allParts.AddSource().Array = new SourceArray();
	allParts.AddProbe();
	allParts.AddColorScheme();
	foreach (var type in ProjectContract.PartKinds.Values) allParts.AddPart(type);
	allParts.Normalize();
	examples.Add(new ProjectDocument(allParts).Write());
	var image = new Project { Scene = new Scene { ImageData = [1, 2, 3] } };
	examples.Add(new ProjectDocument(image).Write());
	File.WriteAllText(fixturePath, JsonSerializer.Serialize(examples));
	return;
}
var output = new StringBuilder("// Generated by _tools/contract_gen. Run `just generate-contract`; do not edit.\nimport { z } from 'zod'\n\n");
var emitted = new HashSet<Type>();
var visiting = new HashSet<Type>();
string Literal(object? value) => JsonSerializer.Serialize(value is Enum ? value.ToString() : value);
string Number(object value) => Convert.ToString(value, CultureInfo.InvariantCulture)!;
string Schema(Type type)
{
	if (type == typeof(string)) return "z.string()";
	if (type == typeof(bool)) return "z.boolean()";
	if (type == typeof(int)) return "z.number().int().min(-2147483648).max(2147483647)";
	if (type == typeof(double)) return "z.number()";
	if (ProjectContract.ItemType(type) is { } item) return $"z.array({Schema(item)})";
	Emit(type);
	return type.Name + "Schema";
}
void Emit(Type type)
{
	if (emitted.Contains(type)) return;
	if (!visiting.Add(type)) throw new NotSupportedException($"Cyclic contract: {type}.");
	string declaration;
	if (type.IsEnum)
	{
		declaration = $"z.enum([{string.Join(", ", Enum.GetNames(type).Select(name => Literal(name)))}])";
	}
	else if (type == typeof(OpticalPart))
	{
		foreach (var part in ProjectContract.PartKinds.Values) Emit(part);
		declaration = $"z.discriminatedUnion('kind', [{string.Join(", ", ProjectContract.PartKinds.Values.Select(part => part.Name + "Schema"))}])";
	}
	else
	{
		var fields = new List<string>();
		if (ProjectContract.HasId(type)) fields.Add("  id: z.uuid(),");
		if (typeof(OpticalPart).IsAssignableFrom(type)) fields.Add($"  kind: z.literal({Literal(ProjectContract.Kind(type))}),");
		foreach (var member in ProjectContract.Objects[type])
		{
			var schema = member.Constant is { } constant ? $"z.literal({Literal(constant)})" : Schema(member.Type);
			if (member.Pattern is { } pattern) schema += $".regex(new RegExp({Literal(pattern)}))";
			if (member.Range is { } range)
			{
				schema += $".{(range.MinimumIsExclusive ? "gt" : "min")}({Number(range.Minimum)})";
				schema += $".{(range.MaximumIsExclusive ? "lt" : "max")}({Number(range.Maximum)})";
			}
			if (member.Nullable) schema += ".nullable()";
			var metadata = new List<string>();
			if (member.Property.GetCustomAttributes(typeof(DefaultValueAttribute), true).FirstOrDefault() is DefaultValueAttribute fallback)
				metadata.Add($"default: {Literal(fallback.Value)}");
			if (member.Property.GetCustomAttributes(typeof(DescriptionAttribute), true).FirstOrDefault() is DescriptionAttribute description)
				metadata.Add($"description: {Literal(description.Description)}");
			if (metadata.Count > 0) schema += $".meta({{ {string.Join(", ", metadata)} }})";
			fields.Add($"  {member.Name}: {schema},");
		}
		if (type == typeof(Scene)) fields.Add("  imageAssetId: z.uuid().nullable(),");
		declaration = "z.strictObject({\n" + string.Join("\n", fields) + "\n})";
	}
	output.Append($"export const {type.Name}Schema = {declaration}\n");
	output.Append($"export type {type.Name} = z.infer<typeof {type.Name}Schema>\n\n");
	visiting.Remove(type);
	emitted.Add(type);
}
Emit(typeof(Project));
var target = Path.Combine(root, "web/src/Api/Project.generated.ts");
var text = output.ToString();
if (args is ["--check"])
{
	if (!File.Exists(target) || File.ReadAllText(target).Replace("\r\n", "\n") != text)
	{
		Console.Error.WriteLine("Project.generated.ts is stale. Run `just generate-contract`.");
		Environment.ExitCode = 1;
	}
}
else if (args.Length == 0) File.WriteAllText(target, text);
else throw new ArgumentException("Use --check or --fixtures <path>.");
